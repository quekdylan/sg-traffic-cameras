#!/usr/bin/env python3
"""Rebuild data/cameras.csv, data/camera_data.h, data/cameras.bin and manifest.json from
data/cameras.json (Singapore) and data/my_cameras.json (Malaysia).

The two JSON files are the source of truth. The CSV, header and binary hold both countries.
The manifest's version only goes up when the camera data actually changes (the JSON or
CSV); camera_data.h carries that version.

Usage:
    python3 tools/build.py
"""
import csv
import datetime
import hashlib
import io
import json
import math
import os
import struct

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
DATA = os.path.join(ROOT, "data")
FILES = ("data/cameras.csv", "data/cameras.json", "data/my_cameras.json", "data/camera_data.h", "data/cameras.bin")
VERSIONED = ("data/cameras.csv", "data/cameras.json", "data/my_cameras.json")  # a change here bumps the version
MY_ID_BASE = 5001  # Malaysian cameras are numbered from here, Singapore ones below it
MY_BOUNDS = (1.2, 7.5, 99.5, 104.7)  # Peninsular Malaysia: lat min, lat max, lon min, lon max
SG_BOUNDS = (1.1, 1.5, 103.5, 104.2)
BIN_MAGIC = b"SGCB"
BIN_FORMAT = 1

TYPES = [  # (code, enum name, label shown on screen)
    (1, "RedLight", "Red light camera"),
    (2, "FixedSpeed", "Speed camera"),
    (3, "MobileSpeed", "Mobile speed camera"),
    (4, "AverageSpeed", "Average speed zone"),
    (5, "LaserSpeed", "Police laser camera"),
    (6, "Violation", "Traffic violation camera"),
]
M_LAT = 110574.0
M_LON = 110574.0 * math.cos(math.radians(1.35))


def metres(a, b):
    return math.hypot((a[0] - b[0]) * M_LAT, (a[1] - b[1]) * M_LON)


def bearing(a, b):
    return round(math.degrees(math.atan2((b[1] - a[1]) * M_LON, (b[0] - a[0]) * M_LAT)) % 360)


def today():
    return datetime.datetime.now(datetime.timezone(datetime.timedelta(hours=8))).date()


def load():
    """The Singapore cameras."""
    with open(os.path.join(DATA, "cameras.json")) as f:
        return json.load(f)


def load_my():
    """The Malaysian cameras (an empty list before the file exists)."""
    path = os.path.join(DATA, "my_cameras.json")
    if not os.path.exists(path):
        return []
    with open(path) as f:
        return json.load(f)


def is_my(cam):
    return int(cam["id"]) >= MY_ID_BASE


def bounds_for(cam):
    return MY_BOUNDS if is_my(cam) else SG_BOUNDS


def cameras_json(cams):
    return json.dumps(sorted(cams, key=lambda c: c["id"]), separators=(",", ":"))


def cameras_csv(cams):
    buf = io.StringIO()
    w = csv.writer(buf)
    w.writerow(["id", "type", "category", "location", "lat", "lon", "bearing_deg", "path_length_m",
                "path_points", "path", "country"])
    for c in cams:
        p = c["path"]
        w.writerow([c["id"], c["type"], c["category"], c["location"], c["lat"], c["lon"], bearing(p[-2], p[-1]),
                    round(sum(metres(a, b) for a, b in zip(p, p[1:]))), len(p),
                    ";".join(f"{a:.6f} {b:.6f}" for a, b in p), "MY" if is_my(c) else "SG"])
    return buf.getvalue()


def packed(cams):
    """(rows, points): rows are (id, type, first point, point count); points in micro-degrees."""
    points, rows = [], []
    for c in cams:
        if not 2 <= len(c["path"]) <= 255:
            raise ValueError(f"camera {c['id']}: path has {len(c['path'])} points (need 2-255)")
        rows.append((c["id"], c["type"], len(points), len(c["path"])))
        points += [(round(lat * 1e6), round(lon * 1e6)) for lat, lon in c["path"]]
    if len(points) > 65535:
        raise ValueError(f"{len(points)} path points (max 65535)")
    return rows, points


def cameras_bin(cams):
    """Same data as camera_data.h, as a little-endian file a device can download and use as is:
    12-byte header ("SGCB", format, camera count, point count, 0), then the points
    (int32 latE6, int32 lonE6) and the cameras (uint16 id, uint8 type, uint8 point count,
    uint16 first point)."""
    rows, points = packed(cams)
    out = struct.pack("<4sHHHH", BIN_MAGIC, BIN_FORMAT, len(rows), len(points), 0)
    out += b"".join(struct.pack("<ii", a, b) for a, b in points)
    out += b"".join(struct.pack("<HBBH", cid, t, n, first) for cid, t, first, n in rows)
    return out


def camera_header(cams, version):
    rows, points = packed(cams)
    out = [
        "#pragma once",
        "#include <stdint.h>",
        "",
        "// Generated by tools/build.py from data/cameras.json and data/my_cameras.json. Do not edit by hand.",
        "// Source: SPF enforcement camera lists (Singapore) and OpenStreetMap (Malaysia, ids from 5001),",
        "// approach paths reviewed in the path editor.",
        "",
        "enum class CameraType : uint8_t {",
        *[f"    {name} = {code}," for code, name, _ in TYPES],
        "};",
        "",
        "inline const char* cameraTypeLabel(CameraType type) {",
        "    switch (type) {",
        *[f'        case CameraType::{name}: return "{label}";' for _, name, label in TYPES],
        "    }",
        '    return "Camera";',
        "}",
        "",
        "// Micro-degrees. A camera's points run from the start of its approach to the camera.",
        "struct CameraPoint {",
        "    int32_t latE6;",
        "    int32_t lonE6;",
        "};",
        "",
        "struct Camera {",
        "    uint16_t id;          // camera id in data/cameras.json or data/my_cameras.json",
        "    CameraType type;",
        "    uint8_t pointCount;   // points in kCameraPoints for this camera",
        "    uint16_t firstPoint;  // index of its first point in kCameraPoints",
        "};",
        "",
        f"static constexpr uint32_t kCameraDataVersion = {version};  // manifest.json version",
        f"static constexpr uint16_t kCameraCount = {len(rows)};",
        f"static constexpr uint16_t kCameraPointCount = {len(points)};",
        "",
        "static const CameraPoint kCameraPoints[kCameraPointCount] = {",
    ]
    for cid, _t, first, n in rows:
        pts = ", ".join(f"{{{a}, {b}}}" for a, b in points[first:first + n])
        out.append(f"    {pts},  // #{cid}")
    out += ["};", "", "static const Camera kCameras[kCameraCount] = {"]
    names = {code: name for code, name, _ in TYPES}
    for cid, t, first, n in rows:
        out.append(f"    {{{cid}, CameraType::{names[t]}, {n}, {first}}},")
    out += ["};", ""]
    return "\n".join(out)


def build(cams, spf_checked=None, my=None):
    """Write all data files and the manifest from the Singapore cameras and the Malaysian
    ones (read from data/my_cameras.json when not given). Returns True if the camera data
    changed."""
    cams = sorted(cams, key=lambda c: c["id"])
    my = sorted(load_my() if my is None else my, key=lambda c: c["id"])
    if any(is_my(c) for c in cams) or not all(is_my(c) for c in my):
        raise ValueError(f"Singapore ids must be below {MY_ID_BASE}, Malaysian ids from {MY_ID_BASE}")
    both = cams + my
    contents = {
        "data/cameras.csv": cameras_csv(both).encode(),
        "data/cameras.json": cameras_json(cams).encode(),
        "data/my_cameras.json": json.dumps(my, separators=(",", ":"), ensure_ascii=False).encode(),
        "data/cameras.bin": cameras_bin(both),
    }
    mpath = os.path.join(ROOT, "manifest.json")
    with open(mpath) as f:
        manifest = json.load(f)
    old = manifest["files"]
    changed = any(old.get(name, {}).get("sha256") != hashlib.sha256(contents[name]).hexdigest()
                  for name in VERSIONED)
    d = today()
    if changed:
        manifest["version"] = max(int(d.strftime("%Y%m%d")), manifest["version"] + 1)
        manifest["updated"] = d.isoformat()
    contents["data/camera_data.h"] = camera_header(both, manifest["version"]).encode()
    files = {k: v for k, v in old.items() if k not in FILES}  # keep other data sets' entries
    for name in FILES:
        raw = contents[name]
        with open(os.path.join(ROOT, name), "wb") as f:
            f.write(raw)
        files[name] = {"bytes": len(raw), "sha256": hashlib.sha256(raw).hexdigest()}
    if spf_checked:
        manifest["spf_checked"] = spf_checked.isoformat()
    manifest["cameras"] = len(both)
    manifest["cameras_sg"] = len(cams)
    manifest["cameras_my"] = len(my)
    manifest["path_points"] = sum(len(c["path"]) for c in both)
    manifest["files"] = files
    with open(mpath, "w") as f:
        f.write(json.dumps(manifest, indent=2) + "\n")
    return changed


if __name__ == "__main__":
    print("data changed" if build(load()) else "no data changes")
